#[test]
fn style_object_parses() {
    let typed: CaptionAutoGenerateArgs = serde_json::from_value(json!({
        "project_id": FIXTURE_PROJECT_ID,
        "from": AUDIO_TRACK_SELECTOR,
        "style": { "font_size_px": 28.0, "color": "#ffffffff" },
    }))
    .expect("args parse");

    match typed.style {
        Some(StyleArg::Object(map)) => {
            assert_eq!(map.get("font_size_px"), Some(&json!(28.0)));
            assert_eq!(map.get("color"), Some(&json!("#ffffffff")));
        }
        other => panic!("expected StyleArg::Object, got {other:?}"),
    }
}

