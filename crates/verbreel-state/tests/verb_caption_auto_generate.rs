const EMPTY_FIXTURE: &str = include_str!("fixtures/empty_project_create.json");
const FIXTURE_PROJECT_ID: &str = "0190b8d3-15e3-7000-bd00-000000000001";
const AUDIO_TRACK_SELECTOR: &str = "track:audio[0]";
const TEXT_TRACK_ID: &str = "0190b8d3-15e3-7000-bd00-0000000aa911";
const SEGMENT_CLIP_ID: &str = "0190b8d3-15e3-7000-bd00-0000000bb911";

fn empty_project() -> Project {
    serde_json::from_str(EMPTY_FIXTURE).expect("empty fixture -> Project")
}

fn fixture_project_id() -> ProjectId {
    empty_project().id
}

fn id<T>(raw: &str) -> T
where
    T: std::str::FromStr,
    T::Err: std::fmt::Debug,
{
    raw.parse().expect("hard-coded UUIDv7 parses")
}

fn args_default() -> CaptionAutoGenerateArgs {
    CaptionAutoGenerateArgs {
        project_id: fixture_project_id(),
        from_selector: AUDIO_TRACK_SELECTOR.to_string(),
        language: None,
        style: None,
        max_line_chars: None,
        to_track: None,
        model: None,
    }
}

fn args_value() -> Value {
    json!({
        "project_id": FIXTURE_PROJECT_ID,
        "from": AUDIO_TRACK_SELECTOR,
    })
}

#[test]
fn args_deserialize_ok_with_all_fields() {
    let raw = json!({
        "project_id": FIXTURE_PROJECT_ID,
        "from": AUDIO_TRACK_SELECTOR,
        "language": "en-US",
        "style": { "font_family": "Inter", "font_size_px": 24.0 },
        "max_line_chars": 42,
        "to_track": "track:0190b8d3-15e3-7000-bd00-0000000aa912",
        "model": "large-v3",
    });
    let typed: CaptionAutoGenerateArgs = serde_json::from_value(raw).expect("args parse");

    assert_eq!(typed.project_id.to_string(), FIXTURE_PROJECT_ID);
    assert_eq!(typed.from_selector, AUDIO_TRACK_SELECTOR);
    assert_eq!(typed.language.as_deref(), Some("en-US"));
    assert_eq!(typed.max_line_chars, Some(42));
    assert_eq!(
        typed.to_track.as_deref(),
        Some("track:0190b8d3-15e3-7000-bd00-0000000aa912")
    );
    assert_eq!(typed.model.as_deref(), Some("large-v3"));
}

